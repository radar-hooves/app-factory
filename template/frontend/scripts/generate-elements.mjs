// `pnpm generate:elements`: the attributes of every element this app places,
// typed. Reads each ELEMENT_ORIGINS app's /elements.d.ts (its own build's,
// vite.elements.config.ts) into src/lib/elements/placed.d.ts, the way
// `generate:api` reads this app's OpenAPI document. ELEMENT_ORIGINS comes from
// backend/.env, or pass the origins: `pnpm generate:elements https://a,https://b`.
import { writeFileSync } from 'node:fs';

const origins = (process.argv[2] ?? process.env.ELEMENT_ORIGINS ?? '')
	.split(',')
	.map((origin) => origin.trim().replace(/\/$/, ''))
	.filter(Boolean);
if (origins.length === 0) {
	console.error('generate:elements: no origins; set ELEMENT_ORIGINS in backend/.env, or pass them');
	process.exit(1);
}

const declarations = await Promise.all(
	origins.map(async (origin) => {
		const response = await fetch(`${origin}/elements.d.ts`);
		if (!response.ok) throw new Error(`${origin}/elements.d.ts answered ${response.status}`);
		return `// ${origin}\n${await response.text()}`;
	})
);
writeFileSync(
	new URL('../src/lib/elements/placed.d.ts', import.meta.url),
	`// Generated by \`pnpm generate:elements\`; do not edit.\n\n${declarations.join('\n')}`
);
