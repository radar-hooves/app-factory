"""`rekey_to_uuid7` over a fixture schema with every key shape a stamped app holds.

Integer keys (identity, serial, bigserial), a v4 key, a self-reference, a
composite key of two foreign keys, a composite foreign key onto it, a natural
text key and a natural composite key. Each test gets its own database.
"""

import datetime
import secrets
import uuid
from collections.abc import Iterator

import pytest
from app_slices import rekey
from app_slices.rekey import MAP_SCHEMA, RekeyError, RekeyMismatch, rekey_to_uuid7
from sqlalchemy import Engine, create_engine, text

SCHEMA = """
CREATE TABLE workspaces (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE people (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE TABLE categories (
    id serial PRIMARY KEY,
    workspace_id integer NOT NULL REFERENCES workspaces (id) ON DELETE RESTRICT,
    parent_id integer REFERENCES categories (id),
    name text NOT NULL
);
CREATE INDEX ix_categories_workspace ON categories (workspace_id);
CREATE TABLE memberships (
    workspace_id integer REFERENCES workspaces (id) ON DELETE CASCADE,
    person_id uuid REFERENCES people (id),
    role text NOT NULL,
    PRIMARY KEY (workspace_id, person_id)
);
CREATE TABLE grants (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    workspace_id integer NOT NULL,
    person_id uuid NOT NULL,
    scope text,
    FOREIGN KEY (workspace_id, person_id) REFERENCES memberships (workspace_id, person_id)
);
CREATE TABLE notes (
    id bigserial PRIMARY KEY,
    category_id integer REFERENCES categories (id),
    body jsonb,
    created_at timestamptz
);
CREATE TABLE profiles (person_id uuid PRIMARY KEY REFERENCES people (id), bio text);
CREATE TABLE settings (key text PRIMARY KEY, value text, updated_by uuid REFERENCES people (id));
CREATE TABLE day_counts (
    person_id uuid REFERENCES people (id),
    day date,
    n integer NOT NULL,
    PRIMARY KEY (person_id, day)
);
"""

T0 = datetime.datetime(2026, 1, 1, tzinfo=datetime.UTC)

# What a reader of the data sees, by names: never by a key, which is what changes.
VIEWS = {
    "workspaces": "SELECT name FROM workspaces ORDER BY id",
    "people": "SELECT name FROM people ORDER BY created_at, id",
    "categories": """SELECT c.name, w.name, p.name FROM categories c JOIN workspaces w ON w.id = c.workspace_id
                     LEFT JOIN categories p ON p.id = c.parent_id ORDER BY c.id""",
    "memberships": """SELECT w.name, p.name, m.role FROM memberships m JOIN workspaces w ON w.id = m.workspace_id
                      JOIN people p ON p.id = m.person_id ORDER BY 1, 2""",
    "grants": """SELECT g.scope, w.name, p.name FROM grants g JOIN memberships m USING (workspace_id, person_id)
                 JOIN workspaces w ON w.id = m.workspace_id JOIN people p ON p.id = m.person_id ORDER BY g.id""",
    "notes": "SELECT n.body::text, c.name FROM notes n LEFT JOIN categories c ON c.id = n.category_id ORDER BY n.id",
    "profiles": "SELECT p.name, f.bio FROM profiles f JOIN people p ON p.id = f.person_id ORDER BY 1",
    "settings": "SELECT s.key, s.value, p.name FROM settings s LEFT JOIN people p ON p.id = s.updated_by ORDER BY 1",
    "day_counts": "SELECT p.name, d.day, d.n FROM day_counts d JOIN people p ON p.id = d.person_id ORDER BY 1, 2",
}


@pytest.fixture
def db(engine: Engine) -> Iterator[Engine]:
    """A database of its own on the suite's Postgres, holding the fixture schema and rows."""
    name = f"rekey_{secrets.token_hex(4)}"
    with engine.connect().execution_options(isolation_level="AUTOCOMMIT") as admin:
        admin.execute(text(f'CREATE DATABASE "{name}"'))
    own = create_engine(engine.url.set(database=name))
    with own.begin() as conn:
        conn.execute(text(SCHEMA))
        _seed(conn)
    yield own
    own.dispose()
    with engine.connect().execution_options(isolation_level="AUTOCOMMIT") as admin:
        admin.execute(text(f'DROP DATABASE "{name}" WITH (FORCE)'))


def _seed(conn: object) -> None:
    run = conn.execute  # type: ignore[attr-defined]
    # Created out of key order, so the order kept is the key's, not the clock's.
    for i, name in enumerate(["home", "circle", "office"]):
        run(
            text("INSERT INTO workspaces (name, created_at) VALUES (:n, :t)"),
            {"n": name, "t": T0 + datetime.timedelta(days=[2, 1, 3][i])},
        )
    # v4 keys, all stamped in the same second: order is created_at, then key.
    for i, name in enumerate(["ada", "bo", "cy", "di"]):
        run(
            text("INSERT INTO people (name, created_at) VALUES (:n, :t)"),
            {"n": name, "t": T0 + datetime.timedelta(seconds=i // 2)},
        )
    run(text("INSERT INTO categories (workspace_id, name) VALUES (1, 'money'), (2, 'stories')"))
    run(text("INSERT INTO categories (workspace_id, parent_id, name) VALUES (1, 1, 'rent'), (1, 3, 'bond')"))
    run(
        text(
            "INSERT INTO memberships SELECT w.id, p.id, 'owner' FROM workspaces w, people p "
            "WHERE (w.name, p.name) IN (('home', 'ada'), ('home', 'bo'), ('circle', 'cy'), ('office', 'ada'))"
        )
    )
    run(
        text(
            "INSERT INTO grants (workspace_id, person_id, scope) SELECT workspace_id, person_id, role FROM memberships"
        )
    )
    for i in range(1200):
        run(
            text("INSERT INTO notes (category_id, body, created_at) VALUES (:c, :b, :t)"),
            {"c": [1, 2, 3, None][i % 4], "b": f'{{"n": {i}}}', "t": None if i % 7 == 0 else T0},
        )
    run(text("INSERT INTO profiles SELECT id, 'likes ' || name FROM people WHERE name <> 'cy'"))
    run(text("INSERT INTO settings SELECT 'theme', 'dark', id FROM people WHERE name = 'bo'"))
    run(text("INSERT INTO settings VALUES ('unset', NULL, NULL)"))
    run(text("INSERT INTO day_counts SELECT id, DATE '2026-11-06', 3 FROM people"))


def _read(db: Engine) -> dict[str, list[tuple[object, ...]]]:
    with db.connect() as conn:
        return {name: [tuple(r) for r in conn.execute(text(sql))] for name, sql in VIEWS.items()}


def _types(db: Engine) -> dict[str, str]:
    with db.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT table_name || '.' || column_name, data_type FROM information_schema.columns "
                "WHERE table_schema = 'public'"
            )
        )
        return {str(r[0]): str(r[1]) for r in rows}


def _constraints(db: Engine) -> list[str]:
    with db.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT conrelid::regclass || ' ' || pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE connamespace = 'public'::regnamespace ORDER BY 1"
            )
        )
        return [r[0] for r in rows]


def test_every_surrogate_key_and_reference_becomes_v7_and_reads_the_same(db: Engine) -> None:
    before, constraints = _read(db), _constraints(db)

    with db.begin() as conn:
        report = rekey_to_uuid7(conn)

    assert report.rekeyed == {"categories": 4, "grants": 4, "notes": 1200, "people": 4, "workspaces": 3}
    assert _read(db) == before
    assert _constraints(db) == constraints
    types = _types(db)
    for col in [
        "workspaces.id",
        "people.id",
        "categories.id",
        "categories.workspace_id",
        "categories.parent_id",
        "memberships.workspace_id",
        "memberships.person_id",
        "grants.id",
        "grants.workspace_id",
        "grants.person_id",
        "notes.id",
        "notes.category_id",
        "profiles.person_id",
        "settings.updated_by",
        "day_counts.person_id",
    ]:
        assert types[col] == "uuid", col
    assert types["settings.key"] == "text"
    assert types["day_counts.day"] == "date"
    with db.connect() as conn:
        for table in report.rekeyed:
            ids: list[uuid.UUID] = list(conn.execute(text(f"SELECT id FROM {table}")).scalars())
            assert {i.version for i in ids} == {7}, table
        # Time from created_at where a row has one; never later than now.
        first: uuid.UUID = conn.execute(text("SELECT id FROM workspaces ORDER BY id LIMIT 1")).scalar_one()
        assert datetime.datetime.fromtimestamp((first.int >> 80) / 1000, datetime.UTC) == T0 + datetime.timedelta(
            days=2
        )
        # No generator is left behind: the app mints keys (P09).
        assert not conn.execute(text("SELECT count(*) FROM pg_sequences WHERE schemaname = 'public'")).scalar()
        assert not conn.execute(
            text(
                "SELECT count(*) FROM information_schema.columns WHERE table_schema = 'public' "
                "AND (column_default IS NOT NULL AND column_name = 'id' OR is_identity = 'YES')"
            )
        ).scalar()
        # A key minted after the rekey sorts after every rekeyed one.
        assert conn.execute(text("SELECT bool_and(id < :new) FROM notes"), {"new": uuid.uuid7()}).scalar()
        assert not conn.execute(
            text("SELECT count(*) FROM pg_namespace WHERE nspname = :s"), {"s": MAP_SCHEMA}
        ).scalar()


def test_a_second_run_changes_nothing(db: Engine) -> None:
    with db.begin() as conn:
        rekey_to_uuid7(conn)
    before = _read(db)
    with db.connect() as conn:
        ids: list[uuid.UUID] = list(conn.execute(text("SELECT id FROM workspaces ORDER BY id")).scalars())

    with db.begin() as conn:
        report = rekey_to_uuid7(conn)

    assert report.rekeyed == {}
    assert _read(db) == before
    with db.connect() as conn:
        assert list(conn.execute(text("SELECT id FROM workspaces ORDER BY id")).scalars()) == ids


def test_a_difference_rolls_everything_back(db: Engine, monkeypatch: pytest.MonkeyPatch) -> None:
    """Keys minted out of order: the proof sees the order change, and nothing is kept."""
    minted = iter(range(10_000, 0, -1))
    monkeypatch.setattr(rekey, "uuid7_at", lambda ms, counter, tail: uuid.UUID(int=next(minted) | (7 << 76)))
    before, types = _read(db), _types(db)

    with pytest.raises(RekeyMismatch, match="before"), db.begin() as conn:
        rekey_to_uuid7(conn)

    assert _types(db) == types
    assert _read(db) == before


def test_a_key_the_database_does_not_generate_is_the_callers_to_name(db: Engine) -> None:
    """Another system's id (a release number, a MusicBrainz id) and a key the app mints look alike here."""
    with db.begin() as conn:
        conn.execute(text("CREATE TABLE releases (id integer PRIMARY KEY, title text)"))
        conn.execute(text("CREATE TABLE recordings (mbid uuid PRIMARY KEY, title text)"))
        conn.execute(text("CREATE TABLE cases (id uuid PRIMARY KEY, title text, created_at timestamptz)"))
        conn.execute(text("CREATE TABLE drafts (id uuid PRIMARY KEY, title text)"))
        conn.execute(text("INSERT INTO releases VALUES (249504, 'Kind of Blue')"))
        conn.execute(text("INSERT INTO recordings VALUES ('5b11f4ce-a62d-471e-81fc-a69a8278c7da', 'So What')"))
        conn.execute(text("INSERT INTO cases VALUES (gen_random_uuid(), 'a matter', now())"))

    undecided = r"cases\.id \(uuid\), recordings\.mbid \(uuid\), releases\.id \(integer\)"
    with pytest.raises(RekeyError, match=undecided), db.begin() as conn:
        rekey_to_uuid7(conn)

    with db.begin() as conn:
        report = rekey_to_uuid7(conn, keep=["releases", "recordings"], include=["cases"])
    assert "cases" in report.rekeyed
    assert "drafts" not in report.rekeyed
    types = _types(db)
    assert (types["releases.id"], types["recordings.mbid"]) == ("integer", "uuid")
    with db.connect() as conn:
        assert (
            conn.execute(text("SELECT mbid::text FROM recordings")).scalar() == "5b11f4ce-a62d-471e-81fc-a69a8278c7da"
        )
        assert conn.execute(text("SELECT id FROM cases")).scalar_one().version == 7


def test_a_mapped_table_keeps_its_old_ids_resolving(db: Engine) -> None:
    with db.connect() as conn:
        old: dict[int, str] = {r[0]: r[1] for r in conn.execute(text("SELECT id, name FROM workspaces"))}

    with db.begin() as conn:
        report = rekey_to_uuid7(conn, mapped=["workspaces"])

    assert report.mapped == ["workspaces"]
    with db.connect() as conn:
        resolved: dict[int, str] = {
            r[0]: r[1]
            for r in conn.execute(
                text(f"SELECT m.old_id, w.name FROM {MAP_SCHEMA}.workspaces m JOIN workspaces w ON w.id = m.new_id")
            )
        }
        assert conn.execute(text(f"SELECT to_regclass('{MAP_SCHEMA}.people')")).scalar() is None
    assert resolved == old


def test_a_text_key_and_a_reference_without_a_foreign_key_are_converted_when_named(db: Engine) -> None:
    with db.begin() as conn:
        conn.execute(text("CREATE TABLE beliefs (id varchar(32) PRIMARY KEY, statement text NOT NULL)"))
        conn.execute(text("CREATE TABLE citations (belief_id varchar(32) REFERENCES beliefs (id), note text)"))
        conn.execute(text("CREATE TABLE alerts (subject_workspace bigint, message text)"))
        conn.execute(text("INSERT INTO beliefs VALUES ('a1b2c3', 'first'), ('ffee00', 'second')"))
        conn.execute(text("INSERT INTO citations VALUES ('ffee00', 'cited'), (NULL, 'none')"))
        conn.execute(text("INSERT INTO alerts VALUES (2, 'about circle'), (NULL, 'about nothing')"))

    with db.begin() as conn:
        rekey_to_uuid7(conn, include=["beliefs"], soft_refs={"alerts.subject_workspace": "workspaces"})

    types = _types(db)
    assert (types["beliefs.id"], types["citations.belief_id"], types["alerts.subject_workspace"]) == ("uuid",) * 3
    with db.connect() as conn:
        assert conn.execute(
            text("SELECT b.statement, c.note FROM citations c LEFT JOIN beliefs b ON b.id = c.belief_id ORDER BY 2")
        ).all() == [("second", "cited"), (None, "none")]
        assert conn.execute(
            text(
                "SELECT w.name, a.message FROM alerts a LEFT JOIN workspaces w ON w.id = a.subject_workspace ORDER BY 2"
            )
        ).all() == [("circle", "about circle"), (None, "about nothing")]


def test_a_reference_to_no_row_is_refused_before_anything_changes(db: Engine) -> None:
    with db.begin() as conn:
        conn.execute(text("CREATE TABLE alerts (subject_workspace integer, message text)"))
        conn.execute(text("INSERT INTO alerts VALUES (99, 'about a workspace long gone')"))

    with (
        pytest.raises(RekeyError, match=r"1 rows of alerts\.subject_workspace name no row of workspaces"),
        db.begin() as conn,
    ):
        rekey_to_uuid7(conn, soft_refs={"alerts.subject_workspace": "workspaces"})
    assert _types(db)["workspaces.id"] == "integer"


def test_a_view_over_a_converted_column_is_refused(db: Engine) -> None:
    with db.begin() as conn:
        conn.execute(text("CREATE VIEW workspace_names AS SELECT id, name FROM workspaces"))

    with pytest.raises(RekeyError, match="workspace_names"), db.begin() as conn:
        rekey_to_uuid7(conn)
