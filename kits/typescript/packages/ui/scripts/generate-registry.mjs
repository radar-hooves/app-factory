#!/usr/bin/env node
/**
 * Generate the situation → component map for @poodle64/ui.
 *
 * WHY THIS EXISTS
 * ---------------
 * A CHI 2026 study (10.1145/3772363.3798616) measured three ways of giving an
 * agent a design system. Letting it RETRIEVE from a component registry hit
 * 95.1% compliance; putting the catalogue in the prompt as prose hit 71.0% with
 * the highest variance. This package already ships the registry the winning arm
 * needs — 40-odd components — yet an audit found 20 of the composed ones never
 * imported at all and every dashboard hand-built from raw Card. The cause is an
 * asymmetry: writing `Card` costs nothing, reaching for `StatCard` costs a
 * lookup. This map removes the lookup. It is keyed by the SITUATION an agent is
 * in ("a share of a bounded whole"), because an agent does not know it wants
 * `ArcGauge` — it knows what it is rendering.
 *
 * WHAT IS GENERATED VS AUTHORED
 * -----------------------------
 * The ONLY hand-authored input is scripts/situations.json — the situation
 * taxonomy, which is irreducible human judgement. Everything else is derived
 * from the package source here:
 *   - the exported component name and its import path (from each index.ts),
 *   - the component's real prop names (from its `$props()` destructuring),
 *   - the guarantee that EVERY shipped component is accounted for.
 * If a shipped component is neither classified under a situation nor named a
 * primitive, this script throws and the build fails — so a new component
 * cannot ship unmapped. That is the whole point: a map that needs someone to
 * remember to update it is the same failure one level down.
 *
 * OUTPUTS (gitignored like dist/, regenerated by build, shipped via "files")
 * --------------------------------------------------------------------------
 *   registry/component-map.md    the dense map an agent reads at the point of need
 *   registry/component-map.json  the same, structured, for machine use
 *
 * `build` runs this first, so a release always carries a freshly-generated map
 * and an unclassified component turns the build red before it can publish.
 *
 * USAGE
 * -----
 *   node scripts/generate-registry.mjs           regenerate the outputs
 *   node scripts/generate-registry.mjs --check    validate the seed against
 *                                                  source and write nothing;
 *                                                  exit 2 on an unclassified,
 *                                                  phantom, or bad-prop entry.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENTS = path.join(PKG, 'src/lib/components/ui');
const SEED = path.join(PKG, 'scripts/situations.json');
const OUT_DIR = path.join(PKG, 'registry');
const OUT_MD = path.join(OUT_DIR, 'component-map.md');
const OUT_JSON = path.join(OUT_DIR, 'component-map.json');
const PKG_NAME = '@poodle64/ui';

const check = process.argv.includes('--check');

/** A build-stopping problem — an unclassified component, a phantom name, a bad prop. */
class RegistryError extends Error {}

// --------------------------------------------------------------------------- //
//  Source readers                                                             //
// --------------------------------------------------------------------------- //

/** kebab-case a PascalCase export name (StatCard -> stat-card). */
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** Every component directory the package ships. */
function shippedDirs() {
	return readdirSync(COMPONENTS)
		.filter((d) => statSync(path.join(COMPONENTS, d)).isDirectory())
		.sort();
}

/**
 * exportName -> dir, by scanning every index.ts. Handles `export { default as
 * StatCard }`, `Root as PasswordInput`, and plain `export { AppNav }`. Only
 * PascalCase names are treated as component exports; lowercase helpers and
 * `type` re-exports are ignored (a type composes nothing on screen).
 */
function exportIndex() {
	const index = new Map();
	for (const dir of shippedDirs()) {
		const idx = path.join(COMPONENTS, dir, 'index.ts');
		if (!existsSync(idx)) continue;
		const src = readFileSync(idx, 'utf8');
		for (const block of src.matchAll(/export\s*\{([^}]*)\}/g)) {
			// A block may carry `type` re-exports mixed in; split and inspect each.
			for (const raw of block[1].split(',')) {
				const token = raw.trim();
				if (!token || token.startsWith('type ')) continue;
				// `X as Y` exports Y; `default as Y` exports Y; bare `X` exports X.
				const asMatch = token.match(/(?:\bas\s+)([A-Za-z0-9_]+)$/);
				const name = asMatch ? asMatch[1] : token;
				if (/^[A-Z]/.test(name) && !index.has(name)) index.set(name, dir);
			}
		}
	}
	return index;
}

/** Locate a component's main .svelte file within its directory. */
function mainSvelte(dir, name) {
	const candidates = [
		path.join(COMPONENTS, dir, `${kebab(name)}.svelte`),
		path.join(COMPONENTS, dir, `${dir}.svelte`)
	];
	for (const c of candidates) if (existsSync(c)) return c;
	// Fall back to the sole .svelte file, if there is exactly one.
	const svelte = readdirSync(path.join(COMPONENTS, dir)).filter((f) => f.endsWith('.svelte'));
	return svelte.length === 1 ? path.join(COMPONENTS, dir, svelte[0]) : null;
}

/**
 * Where a `...rest` spread lands: the component whose props type this file
 * annotates its `$props()` destructuring with. `form-button.svelte` says
 * `let { ref, ...restProps }: ButtonProps = $props()` and imports ButtonProps
 * from '../button/index.js', so its real prop surface is `ref` plus every prop
 * of button.svelte. Only a relative import inside this components tree
 * resolves — a props type from node_modules or a bare specifier returns null
 * and nothing extra is accepted.
 */
function forwardTarget(svelteFile, src, typeName) {
	const named = new RegExp(`\\b${typeName}\\b`);
	const imp = [...src.matchAll(/import\s+([^;]*?)\s+from\s+['"]([^'"]+)['"]/g)].find(
		(m) => named.test(m[1]) && m[2].startsWith('.')
	);
	if (!imp) return null;
	let resolved = path.resolve(path.dirname(svelteFile), imp[2]);
	if (/index\.[cm]?[jt]s$/.test(resolved)) resolved = path.dirname(resolved);
	const dir = path.relative(COMPONENTS, resolved);
	// A sibling component directory, and nothing else.
	if (!dir || dir.startsWith('..') || dir.includes(path.sep)) return null;
	return mainSvelte(dir, typeName.replace(/Props$/, ''));
}

/**
 * The set of prop names a component accepts, read from its `let { ... } =
 * $props()` destructuring — the authoritative list, so a prop named in the seed
 * that no longer exists fails the gate. Returns the source-facing keys: `icon:
 * Icon` -> `icon`, `class: className` -> `class`.
 *
 * A component that spreads `...rest` onto another component of this package
 * accepts that component's props too, so those are unioned in (see
 * forwardTarget). `seen` breaks a cycle between two mutual forwarders.
 */
function propKeys(svelteFile, seen = new Set()) {
	seen.add(svelteFile);
	const src = readFileSync(svelteFile, 'utf8');
	const propsAt = src.indexOf('$props()');
	if (propsAt === -1) return new Set();

	// The nearest `let {` before `$props()` opens the destructuring pattern.
	const before = src.slice(0, propsAt);
	const letMatches = [...before.matchAll(/let\s*\{/g)];
	if (!letMatches.length) return new Set();
	const open = before.indexOf('{', letMatches[letMatches.length - 1].index);

	// Brace-match forward to the pattern's closing `}` (defensive against nesting).
	let depth = 0;
	let end = -1;
	for (let i = open; i < src.length; i++) {
		if (src[i] === '{') depth++;
		else if (src[i] === '}' && --depth === 0) {
			end = i;
			break;
		}
	}
	if (end === -1) return new Set();

	// Split the pattern on top-level commas, respecting (), {}, [] and quotes.
	// Strip any inline comments first — a prop can carry a leading /** ... */ or
	// // ... note inside the pattern (e.g. ContextColumn's ariaLabel).
	const block = src
		.slice(open + 1, end)
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.replace(/\/\/[^\n]*/g, '');
	const parts = [];
	let buf = '';
	let d = 0;
	let quote = '';
	for (const ch of block) {
		if (quote) {
			if (ch === quote) quote = '';
		} else if (ch === '"' || ch === "'" || ch === '`') quote = ch;
		else if ('([{'.includes(ch)) d++;
		else if (')]}'.includes(ch)) d--;
		else if (ch === ',' && d === 0) {
			parts.push(buf);
			buf = '';
			continue;
		}
		buf += ch;
	}
	parts.push(buf);

	const keys = new Set();
	let hasRest = false;
	for (const part of parts) {
		let entry = part.trim();
		if (!entry) continue;
		if (entry.startsWith('...')) {
			hasRest = true;
			continue;
		}
		entry = entry.split('=')[0].trim(); // drop any default value
		const key = (entry.includes(':') ? entry.split(':')[0] : entry).trim(); // `icon: Icon` -> icon
		if (key) keys.add(key);
	}

	// The annotation between the pattern and `$props()` names what the rest
	// spread forwards — `: ButtonProps = ` — so a pure forwarder can be
	// documented by the props it really passes on rather than by `ref` alone.
	if (hasRest) {
		for (const [, typeName] of src
			.slice(end + 1, propsAt)
			.matchAll(/\b([A-Z][A-Za-z0-9_]*Props)\b/g)) {
			const target = forwardTarget(svelteFile, src, typeName);
			if (!target || seen.has(target)) continue;
			for (const k of propKeys(target, seen)) keys.add(k);
		}
	}

	return keys;
}

// --------------------------------------------------------------------------- //
//  Build the model                                                            //
// --------------------------------------------------------------------------- //

function build() {
	const seed = JSON.parse(readFileSync(SEED, 'utf8'));
	const exports = exportIndex();
	const dirs = shippedDirs();
	const version = JSON.parse(readFileSync(path.join(PKG, 'package.json'), 'utf8')).version;

	const problems = [];
	const classifiedDirs = new Set();

	const situations = seed.situations.map((sit) => ({
		key: sit.key,
		title: sit.title,
		description: sit.description,
		components: sit.components.map((c) => {
			const dir = exports.get(c.name);
			if (!dir) {
				problems.push(
					`situations.json names "${c.name}", but no component index.ts exports it (phantom).`
				);
				return { name: c.name, dir: null, import: null, props: c.props, insteadOf: c.insteadOf };
			}
			classifiedDirs.add(dir);

			// Validate every seed prop against the component's real $props().
			const svelte = mainSvelte(dir, c.name);
			const real = svelte ? propKeys(svelte) : null;
			const listed = c.props
				.split(',')
				.map((p) => p.trim().replace(/\?$/, ''))
				.filter(Boolean);
			// An entry with no props is the same failure as an unclassified
			// component: the map names something an agent cannot then use. CI
			// asserts this on the shipped artefact; catching it here turns it
			// red at `pnpm build`, before a tag is cut.
			if (!listed.length) {
				problems.push(
					`${c.name}: no props listed in situations.json — name the props a consumer composes it with.`
				);
			}
			if (real) {
				for (const p of listed) {
					if (!real.has(p)) {
						problems.push(
							`${c.name}: prop "${p}" listed in situations.json is not a prop of ${path.relative(PKG, svelte)}.`
						);
					}
				}
			}
			return {
				name: c.name,
				dir,
				import: `${PKG_NAME}/${dir}`,
				props: c.props,
				insteadOf: c.insteadOf
			};
		})
	}));

	// Coverage: every shipped dir must be classified, a primitive, or type-only.
	const primitives = seed.primitives.components.slice().sort();
	const typeOnly = seed.typeOnly.slice().sort();
	const primitiveSet = new Set(primitives);
	const typeOnlySet = new Set(typeOnly);
	for (const dir of dirs) {
		if (classifiedDirs.has(dir) || primitiveSet.has(dir) || typeOnlySet.has(dir)) continue;
		problems.push(
			`Unclassified component "${dir}" — add it under a situation in scripts/situations.json, or list it in "primitives".`
		);
	}
	// A primitive/type-only name that no longer ships is stale bookkeeping.
	const dirSet = new Set(dirs);
	for (const d of [...primitives, ...typeOnly]) {
		if (!dirSet.has(d)) problems.push(`"${d}" is listed in situations.json but no longer ships.`);
	}

	if (problems.length) {
		throw new RegistryError('Component map is out of sync with the package source:\n  - ' + problems.join('\n  - '));
	}

	return {
		meta: {
			package: PKG_NAME,
			version,
			generatedBy: 'scripts/generate-registry.mjs',
			source: 'scripts/situations.json + package source (DO NOT EDIT the outputs by hand)',
			componentCount: dirs.length,
			situationCount: situations.length
		},
		situations,
		primitives: primitives.map((dir) => ({ dir, import: `${PKG_NAME}/${dir}` }))
	};
}

// --------------------------------------------------------------------------- //
//  Render                                                                     //
// --------------------------------------------------------------------------- //

function renderMarkdown(model) {
	const L = [];
	L.push(`# ${PKG_NAME} — situation → component map`);
	L.push('');
	L.push(
		`<!-- GENERATED by scripts/generate-registry.mjs from scripts/situations.json + package source. DO NOT EDIT. -->`
	);
	L.push(
		`Generated from \`${PKG_NAME}@${model.meta.version}\`. ${model.meta.componentCount} components, ${model.meta.situationCount} situations.`
	);
	L.push('');
	L.push(
		'**Read this before writing a `<div>`.** Find the SITUATION you are in below, then compose the component named for it — do not hand-build it from raw `Card` or utility classes. Import is `import { Name } from \'<import path>\'`. Props marked `?` are optional. This map is the retrieval step the [`frontend-design` skill] makes mandatory; the [CHI 2026 study] measured composing-from-a-registry at 95% design-system compliance against 71% for writing the CSS from a prose style guide.'
	);
	L.push('');
	L.push('[`frontend-design` skill]: the household rule that loads before any UI code.');
	L.push('[CHI 2026 study]: 10.1145/3772363.3798616');
	L.push('');

	for (const sit of model.situations) {
		L.push(`## ${sit.title}`);
		L.push('');
		L.push(`_${sit.description}_`);
		L.push('');
		L.push('| Component | Import | Key props | Reach for it instead of |');
		L.push('| --- | --- | --- | --- |');
		for (const c of sit.components) {
			L.push(`| \`${c.name}\` | \`${c.import}\` | \`${c.props}\` | ${c.insteadOf} |`);
		}
		L.push('');
	}

	L.push('## Primitives you already know');
	L.push('');
	L.push(
		'_Standard shadcn-svelte / bits-ui primitives — reach for them the same way; no situation lookup needed. Import each from its path below._'
	);
	L.push('');
	L.push(model.primitives.map((p) => `\`${p.import}\``).join(' · '));
	L.push('');

	return L.join('\n') + '\n';
}

// --------------------------------------------------------------------------- //
//  Main                                                                       //
// --------------------------------------------------------------------------- //

function main() {
	let model;
	try {
		model = build();
	} catch (err) {
		if (err instanceof RegistryError) {
			console.error(`\n✗ ${err.message}\n`);
			process.exit(2);
		}
		throw err;
	}

	if (check) {
		// build() already validated (it throws on any problem); reaching here is a pass.
		renderMarkdown(model); // exercise the renderer too, so a render bug is caught
		console.log(`✓ Component map valid: ${model.meta.componentCount} components, all classified.`);
		return;
	}

	const md = renderMarkdown(model);
	const json = JSON.stringify(model, null, '\t') + '\n';
	if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
	writeFileSync(OUT_MD, md);
	writeFileSync(OUT_JSON, json);
	console.log(
		`✓ Wrote ${path.relative(PKG, OUT_MD)} and ${path.relative(PKG, OUT_JSON)} (${model.meta.situationCount} situations, ${model.meta.componentCount} components).`
	);
}

main();
